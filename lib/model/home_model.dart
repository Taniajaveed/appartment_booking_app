class HomeModel {
  final String imageName;
  final String title;
  final String price;
  final String location;
  final String bedrooms;
  final String bathrooms;
  final String area;
  final String id;

  HomeModel({
    required this.imageName,
    required this.title,
    required this.price,
    required this.location,
    required this.bedrooms,
    required this.bathrooms,
    required this.area,
    required this.id,
  });
}
